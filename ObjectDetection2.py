from ultralytics import YOLO

class SkiJumperDetector:
    def __init__(self, model_path='models/best.pt', conf_th=0.5, iou_th=0.5, imgsz=640):
        self.model = YOLO(model_path)
        self.conf_th = float(conf_th)
        self.iou_th = float(iou_th)
        self.imgsz = int(imgsz)
        self.JUMPER_CLASS = 0  # COCO: person

    def detect_and_track(self, frame_bgr, conf_th=None, imgsz=None):
        # allow per-call overrides
        conf = self.conf_th if conf_th is None else float(conf_th)
        sz = self.imgsz if imgsz is None else int(imgsz)

        results = self.model.track(
          frame_bgr,
          conf=conf,
          iou=self.iou_th,
          imgsz=sz,
          persist = True,
          verbose=False,
          classes=[self.JUMPER_CLASS]
        )[0]

        dets = []
        if results.boxes is None or results.boxes.id is None:
          if results.boxes is None:
              return dets

        for b in results.boxes:
          cls = int(b.cls.item())
          confb = float(b.conf.item())
          xyxy = b.xyxy[0].cpu().numpy().astype(np.float32)

          tid = int(b.id.item()) if b.id is not None else None

          dets.append(Detection(
            xyxy=xyxy,
            conf=confb,
            cls=cls,
            track_id=tid
          ))
        return dets

