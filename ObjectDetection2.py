from segment_anything import sam_model_registry, SamPredictor
import torch

class SAMSegmenter:
  def __init__(self, model_type="vit_b", checkpoint="models/sam_vit_b_01ec64.pth"):
    self.device = "cuda" if torch.cuda.is_available() else "cpu"
    sam = sam_model_registry[model_type](checkpoint=checkpoint)
    sam.to(device=self.device)
    self.predictor = SamPredictor(sam)

  def get_com(self, frame, bbox):
    self.predictor.set_image(frame)
    input_box = np.array(bbox)

    masks, scores, _ = self.predictor.predict(
        box=input_box[None, :],
        multimask_output=False
    )
    mask = masks[0]

    M = cv2.moments(mask.astype(np.uint8))
    if M["m00"] != 0:
      cX = int(M["m10"] / M["m00"])
      cY = int(M["m01"] / M["m00"])
      return (cX, cY), mask
    return None, None

"""**data structures + helper**"""

import cv2
import numpy as np
from dataclasses import dataclass

@dataclass
class Detection:
    xyxy: np.ndarray   # (4,) float32
    conf: float
    cls: int
    track_id: int | None = None

def clamp_box(xyxy, w, h):
    x1, y1, x2, y2 = xyxy
    x1 = max(0, min(int(x1), w - 1))
    y1 = max(0, min(int(y1), h - 1))
    x2 = max(0, min(int(x2), w - 1))
    y2 = max(0, min(int(y2), h - 1))
    if x2 <= x1: x2 = min(w - 1, x1 + 1)
    if y2 <= y1: y2 = min(h - 1, y1 + 1)
    return np.array([x1, y1, x2, y2], dtype=np.int32)

def xyxy_center(xyxy: np.ndarray) -> np.ndarray:
    x1, y1, x2, y2 = xyxy
    return np.array([(x1 + x2) / 2.0, (y1 + y2) / 2.0], dtype=np.float32)

def adaptive_crop(frame_bgr, xyxy, scale=2.2):
    h, w = frame_bgr.shape[:2]
    x1, y1, x2, y2 = xyxy
    cx, cy = (x1 + x2) / 2, (y1 + y2) / 2
    bw, bh = (x2 - x1), (y2 - y1)

    bw2, bh2 = bw * scale / 2, bh * scale / 2
    crop_xyxy = np.array([cx - bw2, cy - bh2, cx + bw2, cy + bh2], dtype=np.float32)
    crop_xyxy = clamp_box(crop_xyxy, w, h)

    x1, y1, x2, y2 = crop_xyxy
    roi = frame_bgr[y1:y2, x1:x2].copy()
    return roi, crop_xyxy

def measurement_from(det: Detection, pose_com: np.ndarray | None, prefer_pose=True) -> np.ndarray:
    if prefer_pose and pose_com is not None:
        return pose_com
    return xyxy_center(det.xyxy)

