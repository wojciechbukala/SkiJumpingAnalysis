import mediapipe as mp
from mediapipe.tasks import python
from mediapipe.tasks.python import vision

class MediaPipePoseROI:
    def __init__(self, model_path: str, num_poses: int = 1):
        base_options = python.BaseOptions(model_asset_path=model_path)

        options = vision.PoseLandmarkerOptions(
            base_options=base_options,
            running_mode=vision.RunningMode.VIDEO,
            num_poses=num_poses,
            output_segmentation_masks=False,
        )
        self.landmarker = vision.PoseLandmarker.create_from_options(options)

    def estimate_com(self, roi_bgr: np.ndarray, crop_xyxy: np.ndarray, timestamp_ms: int) -> tuple[np.ndarray | None, float]:
        if roi_bgr is None or roi_bgr.size == 0:
            return None, 0.0

        roi_rgb = cv2.cvtColor(roi_bgr, cv2.COLOR_BGR2RGB)
        mp_image = mp.Image(image_format=mp.ImageFormat.SRGB, data=roi_rgb)

        result = self.landmarker.detect_for_video(mp_image, timestamp_ms)
        if result.pose_landmarks is None or len(result.pose_landmarks) == 0:
            return None, 0.0

        lms = result.pose_landmarks[0]
        idxs = [11, 12, 23, 24]  # shoulders + hips

        pts = np.array([[lms[i].x, lms[i].y] for i in idxs], dtype=np.float32)

        vis_list = []
        for i in idxs:
            v = getattr(lms[i], "visibility", None)
            if v is not None:
                vis_list.append(float(v))
        score = float(np.mean(vis_list)) if len(vis_list) else 1.0

        if score < 0.4:
            return None, score

        roi_h, roi_w = roi_rgb.shape[:2]
        com_roi = np.array([pts[:, 0].mean() * roi_w, pts[:, 1].mean() * roi_h], dtype=np.float32)

        x1, y1, x2, y2 = crop_xyxy
        com_img = np.array([com_roi[0] + x1, com_roi[1] + y1], dtype=np.float32)
        return com_img, score

"""**Kalman filter (position + speed)**"""

from filterpy.kalman import KalmanFilter

class Kalman2D:
    def __init__(self, dt=1/30, process_var=200, meas_var=0.05):
        self.kf = KalmanFilter(dim_x=4, dim_z=2)

        self.kf.F = np.array([
            [1, 0, dt, 0],
            [0, 1, 0, dt],
            [0, 0, 1,  0],
            [0, 0, 0,  1],
        ], dtype=np.float32)

        self.kf.H = np.array([
            [1, 0, 0, 0],
            [0, 1, 0, 0],
        ], dtype=np.float32)

        self.kf.P *= 100.0
        self.kf.R = np.eye(2, dtype=np.float32) * meas_var

        q = process_var
        self.kf.Q = np.array([
            [0.25*dt**4, 0, 0.5*dt**3, 0],
            [0, 0.25*dt**4, 0, 0.5*dt**3],
            [0.5*dt**3, 0, dt**2, 0],
            [0, 0.5*dt**3, 0, dt**2],
        ], dtype=np.float32) * q

        self.initialized = False

    def init(self, z: np.ndarray):
        self.kf.x = np.array([z[0], z[1], 0.0, 0.0], dtype=np.float32)
        self.initialized = True

    def predict_only(self) -> np.ndarray:
    # ONE prediction per frame
      self.kf.predict()
      return self.kf.x[:2].reshape(-1).copy()

    def update(self, z: np.ndarray | None) -> np.ndarray:
        # NO predict here (predict already done via predict_only)
        if z is not None:
            if not self.initialized:
                self.init(z)
            self.kf.update(z)
        return self.kf.x[:2].copy()

