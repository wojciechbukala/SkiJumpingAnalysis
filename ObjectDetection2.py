import os
import csv
import numpy as np
import cv2


def run_pipeline(
    video_path: str,
    out_video_path: str = "/outputs/output_result.mp4",
    out_csv_path: str = "/outputs/trajectory_2d.csv",
    yolo_model: str = "/models/best.pt",
    conf_th: float = 0.5,
    use_pose: bool = False,
    pose_model_path: str = "pose_landmarker_lite.task",
    use_sam = False
):
    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        raise RuntimeError(f"Cannot open video: {video_path}")

    fps = cap.get(cv2.CAP_PROP_FPS)
    dt = 1.0 / fps if (fps and fps > 1) else 1 / 30

    W = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    H = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))

    fourcc = cv2.VideoWriter_fourcc(*"mp4v")
    out = cv2.VideoWriter(
        out_video_path,
        fourcc,
        float(fps if fps and fps > 1 else 30),
        (W, H),
    )

    detector = SkiJumperDetector(
        model_path=yolo_model,
        conf_th=conf_th,
        imgsz=640
    )

    pose = None
    if use_pose:
        if not os.path.exists(pose_model_path):
            raise RuntimeError(
                f"Pose model not found: {pose_model_path}. Run CELL 1 first."
            )
        pose = MediaPipePoseROI(model_path=pose_model_path)

    sam = None
    if use_sam:
      sam = SAMSegmenter()

    kf = Kalman2D(dt=dt)

    with open(out_csv_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(
            ["frame", "track_id","x1", "y1", "x2", "y2", "meas_x", "meas_y", "kf_x", "kf_y", "pose_score", "used_pose", "used_sam"]
        )

        frame_idx = 0

        # While for each frame
        while True:
            ok, frame = cap.read()
            if not ok:
                break

            # 0) KF PREDICT (ONCE PER FRAME)
            kf_pred = kf.predict_only()


            # 1) DETECTION: FULL-FRAME OR ROI WHEN LOST
            detections = detector.detect_and_track(frame)

            main_jumper = pick_best_detection(detections, kf_pred)

            meas = None
            pose_score = 0.0
            used_pose = 0

            if main_jumper is not None:
              current_meas = xyxy_center(main_jumper.xyxy)

              # detect camera change
              dist = np.sqrt((current_meas[0] - kf_pred[0])**2 + (current_meas[1] - kf_pred[1])**2)

              if dist > 300:
                  kf.init(current_meas)


              # MediaPipe Pose
              roi_pose, crop_xyxy = adaptive_crop(frame, main_jumper.xyxy, scale=2.0)

              if pose:
                timestamp_ms = int(frame_idx * dt * 1000)
                pose_com, pose_score = pose.estimate_com(roi_pose, crop_xyxy, timestamp_ms)
              else:
                pose_com = None

              if pose_com is not None:
                meas = pose_com
                used_pose = 1
                color_point = (0, 255, 255)
              else:
                meas = xyxy_center(main_jumper.xyxy)
                used_pose = 0
                color_point = (255, 255, 0)

              # SAM
              used_sam = 0
              if sam:
                sam_com, jumper_mask = sam.get_com(frame, main_jumper.xyxy)

                if sam_com is not None:
                  meas = sam_com
                  used_sam = 1
                  color_point = (0, 0, 255)
                else:
                  meas = xyxy_center(main_jumper.xyxy)
                  used_sam = 0
                  color_point = (255, 255, 0)

              # Drawing
              x1, y1, x2, y2 = map(int, main_jumper.xyxy)
              cv2.rectangle(frame, (x1, y1), (x2, y2), (0, 255, 0), 2)
              cv2.putText(frame, f"ID:{main_jumper.track_id}", (x1, max(0, y1-10)),
                          cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0, 255, 0), 2)
              cv2.circle(frame, (int(meas[0]), int(meas[1])), 8, color_point, -1)

              # KALMAN UPDATE + DRAW
              kf_pos = kf.update(meas)
              cv2.circle(frame, (int(kf_pos[0]), int(kf_pos[1])), 8, (255, 0, 0), -1)

              # LOG + CSV LOG
              print(f"Frame: {frame_idx} - TrackID: {main_jumper.track_id} - Meas_x: {meas[0]} - Meas_y: {meas[1]} - Kf_x: {kf_pos[0]} - Kf_y: {kf_pos[1]}")
              row = [frame_idx, main_jumper.track_id, x1, y1, x2, y2,
                    float(meas[0]) if meas is not None else None,
                    float(meas[1]) if meas is not None else None,
                    kf_pos[0], kf_pos[1], pose_score, used_pose, used_sam]
              writer.writerow(row)

              out.write(frame)
            frame_idx += 1

    cap.release()
    out.release()

    print("Saved video:", out_video_path)
    print("Saved csv:", out_csv_path)

