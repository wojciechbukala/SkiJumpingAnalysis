def pick_main_track(tracked: list[Detection], last_main_id: int | None = None) -> Detection | None:
    if not tracked:
        return None

    # if jumper already tracked
    if last_main_id is not None:
      for d in tracked:
        if d.track_id == last_main_id:
          return d

    # if no ID (start or lost bounding box)
    def area(d: Detection):
        x1, y1, x2, y2 = d.xyxy
        return max(0.0, (x2 - x1)) * max(0.0, (y2 - y1))

    return max(tracked, key=area)

def pick_best_detection(tracked_dets, kf_pos):
  if not tracked_dets:
    return None

  if len(tracked_dets) == 1:
    return tracked_dets[0]

  def dist_to_kf(d):
    cx, cy = xyxy_center(d.xyxy)
    return np.sqrt((cx - kf_pos[0])**2 + (cy - kf_pos[1])**2)

  return min(tracked_dets, key=dist_to_kf)

